def citation_repair_prompt(
    invalid: list[tuple[str, str, str]],
    verdict_problem: str | None = None,
) -> str:
    parts = [
        "Служебная проверка обнаружила проблему в черновике. "
        "Ответь заново на исходный вопрос. Компания и цель не менялись."
    ]
    if invalid:
        parts.append("Проблемные цитаты:")
        for claim, path, why in invalid:
            parts.append(f"Утверждение: {claim!r}; адрес: {path!r}; причина: {why}")
        parts.append(
            "Исправь одновременно текст и цитату по данным инструмента. "
            "Не подставляй случайный существующий адрес. "
            "Если подтверждения нет, убери факт и обозначь пробел."
        )
    if verdict_problem:
        parts.append("Дополнительная проблема: " + verdict_problem)
        parts.append("Наличие других данных не заполняет отсутствующее поле.")
    parts.append(
        "При необходимости вызови инструмент с установленным ИНН. "
        "Не повторяй уже успешный вызов без причины. "
        "Сохрани верные факты и дату. Не показывай пользователю "
        "служебные сообщения проверки."
    )
    return "\n\n".join(parts)
